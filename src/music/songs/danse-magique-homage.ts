import type { SongDefinition } from './types';

/** [pitch, start, length, vel, pan] */
type N = [number, number, number, number, number];

const B = 16; // steps per bar

function n(pitch: number, bar: number, beat: number, lenBeats: number, vel = 0.75, pan = 0): N {
  const start = bar * B + beat * 4;
  const length = Math.max(1, lenBeats * 4);
  return [pitch, start, length, vel, pan];
}

/** 16th-grid note inside a pattern (bar 0-based, step 0..15 within bar). */
function s(pitch: number, bar: number, step: number, lenSteps: number, vel = 0.75, pan = 0): N {
  return [pitch, bar * B + step, Math.max(1, lenSteps), vel, pan];
}

function flat(notes: N[]): string {
  return notes.map((x) => x.join(', ')).join(', ');
}

